using System.Collections;
using System.ComponentModel;
using System.Data;
using System.Diagnostics.CodeAnalysis;

namespace Toolbox.BindingTable
{
    public static class BindingExtension
    {
        /// <summary>
        /// Copies BindingTableRows to a new Table using CopyToDataTable.
        /// </summary>
        /// <typeparam name="T"></typeparam>
        /// <param name="data"></param>
        /// <returns></returns>
        /// <see cref="DataTableExtensions.CopyToDataTable"/>
        public static DataTable ToDataTable<T>(this IEnumerable<T> data)
            where T : BindingTableRow, new()
        {
            DataTable result;
            DataColumn[] dataColumns = new T().ColumnDefinitions().ToArray();

            IList<DataRow> values = data.Select(s => s.GetRow()).ToList();

            if (values.Count == 0)
            {
                // CopyToDataTable returns a Invalid Operation Exception if there are no rows in the list.
                // Return an empty table in that scenario.
                using (result = new DataTable())
                {
                    if (data is IBindingTable source)
                    { result.TableName = data.GetType().FullName; }

                    result.AddColumns(dataColumns.ToArray()); 
                }
            }
            else
            {
                result = values.CopyToDataTable();

                if (data is IBindingTable source)
                { result.TableName = data.GetType().FullName; }
            }


            return result;
        }

        /// <inheritdoc cref="List{T}.AddRange(IEnumerable{T})"/>
        public static void AddRange<T>(this BindingList<T> target, params IEnumerable<T> source)
        {
            foreach (T item in source.ToList())
            { target.Add(item); }
        }

        /// <summary>
        /// Executes <see cref="Enumerable.Single{TSource}(IEnumerable{TSource})"/>
        /// except the statement is pre-wrapped in a Try/Catch block and does not return the exception.
        /// </summary>
        /// <typeparam name="TSource"></typeparam>
        /// <param name="source"></param>
        /// <param name="value"></param>
        /// <returns></returns>
        public static Boolean TryGetSingle<TSource>(this IEnumerable<TSource> source, [NotNullWhen(true)] out TSource? value)
        { return source.TryGetSingle(w => true, out value, out _); }

        /// <summary>
        /// Executes <see cref="Enumerable.Single{TSource}(IEnumerable{TSource})"/>
        /// except the statement is pre-wrapped in a Try/Catch block and returns the exception as an out parameter.
        /// </summary>
        /// <typeparam name="TSource"></typeparam>
        /// <param name="source"></param>
        /// <param name="value"></param>
        /// <param name="exception"></param>
        /// <returns></returns>
        public static Boolean TryGetSingle<TSource>(this IEnumerable<TSource> source, [NotNullWhen(true)] out TSource? value, [NotNullWhen(false)] out Exception? exception)
        { return source.TryGetSingle(w => true, out value, out exception); }

        /// <summary>
        /// Executes <see cref="Enumerable.Single{TSource}(IEnumerable{TSource}, Func{TSource, bool})"/>
        /// except the statement is pre-wrapped in a Try/Catch block and does not return the exception.
        /// </summary>
        /// <typeparam name="TSource"></typeparam>
        /// <param name="source"></param>
        /// <param name="predicate">A function to test each element for a condition.</param>
        /// <param name="value">The Single value in <paramref name="source"/> that matched the <paramref name="predicate"/></param>
        /// <returns></returns>
        public static Boolean TryGetSingle<TSource>(this IEnumerable<TSource> source, Func<TSource, Boolean> predicate, [NotNullWhen(true)] out TSource? value)
        { return source.TryGetSingle(predicate, out value, out _); }

        /// <summary>
        /// Executes <see cref="Enumerable.Single{TSource}(IEnumerable{TSource}, Func{TSource, bool})"/>
        /// except the statement is pre-wrapped in a Try/Catch block and returns the exception as an out parameter.
        /// </summary>
        /// <typeparam name="TSource"></typeparam>
        /// <param name="source"></param>
        /// <param name="predicate">A function to test each element for a condition.</param>
        /// <param name="value">The Single value in <paramref name="source"/> that matched the <paramref name="predicate"/></param>
        /// <param name="exception">Exception that was generated by IEnumerable{TSource}.Single, if any.</param>
        /// <returns><see langword="true"/> if exactly one matching element was found and no exception occurred; otherwise <see langword="false"/> and the exception is returned.</returns>
        public static Boolean TryGetSingle<TSource>(this IEnumerable<TSource> source, Func<TSource, Boolean> predicate, [NotNullWhen(true)] out TSource? value, [NotNullWhen(false)] out Exception? exception)
        {   //TODO: Need to find all the places where this should be used.
            //Most will use an If(IEnumerable{TSource}.FirstOrDefault() is {TSource} value).

            value = default;
            exception = null;

            try
            { value = source.Single(w => predicate(w)); return value is TSource; }
            catch (Exception ex)
            {
                exception = ex;
                exception.Data.Add(nameof(source), source.GetType().Name);
                exception.Data.Add(nameof(IList.Count), source.Count(w => predicate(w)));
            }

            return exception is null;
        }
    }

    static class BindingPrivateExtension
    {
        /// <summary>
        /// Adds columns to the target table, if the column does not already exist.
        /// </summary>
        /// <param name="target"></param>
        /// <param name="columns"></param>
        /// <param name="allowDBNull"></param>
        public static void AddColumns(this DataTable target, IReadOnlyList<DataColumn> columns, Boolean? allowDBNull = null)
        {
            foreach (DataColumn item in columns)
            {
                using (DataColumn column = new DataColumn(item.ColumnName, item.DataType)
                {
                    AllowDBNull = item.AllowDBNull,
                    Caption = item.Caption,
                    DefaultValue = item.DefaultValue,
                })
                {
                    if (allowDBNull is Boolean value) { column.AllowDBNull = value; }

                    if (!target.Columns.Contains(column.ColumnName)) { target.Columns.Add(column); }
                }
            }
        }
    }
}
